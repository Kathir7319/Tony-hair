// Business Hours Real-Time Checker
function setupBusinessHoursStatus() {
  const statusEl = document.getElementById("liveHoursBadge");
  if (!statusEl) return;

  function checkStatus() {
    const now = new Date();
    const etTimeString = now.toLocaleString("en-US", { timeZone: "America/New_York" });
    const etDate = new Date(etTimeString);
    const day = etDate.getDay();
    const hours = etDate.getHours();
    const minutes = etDate.getMinutes();
    const currentMins = hours * 60 + minutes;

    const openMins = 10 * 60; // 10:00 AM
    const closeMins = 19 * 60 + 30; // 7:30 PM

    let isOpen = false;
    let isMonday = (day === 1);

    if (!isMonday && currentMins >= openMins && currentMins < closeMins) {
      isOpen = true;
    }

    if (isMonday) {
      statusEl.className = "badge-pill badge-closed";
      statusEl.innerHTML = `<span class="status-dot"></span> <span>${i18n[currentLang].status_monday}</span>`;
    } else if (isOpen) {
      statusEl.className = "badge-pill badge-open";
      statusEl.innerHTML = `<span class="status-dot"></span> <span>${i18n[currentLang].status_open}</span>`;
    } else {
      statusEl.className = "badge-pill badge-closed";
      statusEl.innerHTML = `<span class="status-dot"></span> <span>${i18n[currentLang].status_closed}</span>`;
    }
  }

  checkStatus();
  setInterval(checkStatus, 60000);
}

