// Clean URLs Support & Address Bar Enhancer
function setupCleanURLs() {
  try {
    // 1. Remove .html from the address bar seamlessly on HTTP/HTTPS
    if (window.location.protocol.startsWith("http") && window.location.pathname.endsWith(".html")) {
      let cleanPath = window.location.pathname.replace(/\.html$/, "");
      if (cleanPath.endsWith("/index")) {
        cleanPath = cleanPath.replace(/\/index$/, "") || "/";
      }
      const cleanUrl = cleanPath + window.location.search + window.location.hash;
      window.history.replaceState(null, "", cleanUrl);
    }

    // 2. Highlight current active navigation tab based on clean path
    const rawPath = window.location.pathname;
    const cleanPath = rawPath.replace(/\/$/, "").replace(/\.html$/, "").toLowerCase() || "/";
    const navLinks = document.querySelectorAll("#mainNav .nav-link");

    navLinks.forEach(link => {
      const href = (link.getAttribute("href") || "").replace(/\/$/, "").replace(/\.html$/, "").toLowerCase() || "/";
      const isHome = (cleanPath === "/" || cleanPath === "" || cleanPath.endsWith("index")) && (href === "/" || href === "");
      const isMatch = isHome || (cleanPath.endsWith(href) && href !== "/");

      if (isMatch) {
        link.classList.add("current");
      } else {
        link.classList.remove("current");
      }
    });

    // 3. Fallback for offline desktop file:// protocol
    if (window.location.protocol === "file:") {
      document.querySelectorAll("a[href]").forEach(a => {
        const href = a.getAttribute("href");
        if (href && !href.startsWith("http") && !href.startsWith("#") && !href.startsWith("tel:") && !href.startsWith("mailto:")) {
          if (href === "/" || href === "./") {
            a.setAttribute("href", "index.html");
          } else if (!href.includes(".") && !href.endsWith("/")) {
            a.setAttribute("href", href + ".html");
          }
        }
      });
    }
  } catch (err) {
    console.debug("Clean URLs setup note:", err);
  }
}

